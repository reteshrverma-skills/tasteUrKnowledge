-- Countries, and the country each parent and child registered from.
-- Prisma: Country, UserProfile.countryCode
--
-- country: every ISO 3166-1 country - its two-letter code, English name and
-- international dialling code (NULL for the few uninhabited territories that
-- have none). sortOrder puts the United Kingdom first in the drop-downs; the
-- rest follow alphabetically. isActive = false hides a country from the forms
-- without deleting it.
--
-- userProfile.countryCode: nullable, because accounts made before this
-- migration have no country recorded. New sign-ups and new children must pick
-- one. The foreign key stops a code that is not in the table.
--
-- Safe to run more than once: the table, rows, column, key and index are all
-- only created when missing.
--
-- Run once:  npx prisma db execute --file prisma/sql/031_country.sql --schema prisma/schema.prisma

