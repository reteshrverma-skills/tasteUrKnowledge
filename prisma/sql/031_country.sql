    "sortOrder" SMALLINT NOT NULL DEFAULT 100,
    "isActive"  BOOLEAN  NOT NULL DEFAULT TRUE,
    CONSTRAINT country_code_format CHECK ("code" ~ '^[A-Z]{2}$')
);

