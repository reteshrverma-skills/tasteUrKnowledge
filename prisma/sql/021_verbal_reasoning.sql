-- Verbal Reasoning: question bank and test tracker.
-- Applied by hand on 2026-10-12; recorded here to match the live tables.
-- Prisma models: GsVrQuestion, TestTrackerVrMain, TestTrackerVr.

-- =====================================================
-- 1. Verbal Reasoning Question Bank
-- =====================================================

CREATE TABLE IF NOT EXISTS "gsVRQuestions" (
    "id" BIGINT NOT NULL,
    "topic" VARCHAR(255),
    "subTopic" VARCHAR(255),
    "quest" TEXT,
    "optionA" TEXT,
    "optionB" TEXT,
    "optionC" TEXT,
    "optionD" TEXT,
    "optionE" TEXT,
    "ansChoice" VARCHAR(10),
    "explanation" TEXT,
    "difficultyLevel" VARCHAR(50),
    "yearName" VARCHAR(50),
    "whyWrongA" TEXT,
    "whyWrongB" TEXT,
    "whyWrongC" TEXT,
    "whyWrongD" TEXT,
    "whyWrongE" TEXT,
    CONSTRAINT "pk_gsVRQuestions"
        PRIMARY KEY ("id")
);

-- =====================================================
-- 2. Main Test Session Tracker - one record per test session
-- =====================================================

CREATE TABLE IF NOT EXISTS "testTrackerVRMain" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "studentId" BIGINT,
    "testStartTime" TIMESTAMP,
    "topic" VARCHAR(255),
    "subTopic" VARCHAR(255),
    "difficultyLevel" VARCHAR(50),
    "completionReason" VARCHAR(100),
    CONSTRAINT "pk_testTrackerVRMain"
        PRIMARY KEY ("id")
);

-- =====================================================
-- 3. Individual Question Attempt Tracker - one record per question in a test
-- =====================================================

CREATE TABLE IF NOT EXISTS "testTrackerVR" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "questionId" BIGINT,
    "studentId" BIGINT,
    "isAnsRight" BOOLEAN,
    "isSkipped" BOOLEAN,
    "testId" BIGINT,
    "timeSpentOnQuestion" NUMERIC(10,2),
    "chosenOption" VARCHAR(10),
    "correctOption" VARCHAR(10),
    "questionOrder" SMALLINT,

    CONSTRAINT "pk_testTrackerVR"
        PRIMARY KEY ("id"),

    CONSTRAINT "fk_testTrackerVR_question"
        FOREIGN KEY ("questionId")
        REFERENCES "gsVRQuestions" ("id")
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,

    CONSTRAINT "fk_testTrackerVR_test"
        FOREIGN KEY ("testId")
        REFERENCES "testTrackerVRMain" ("id")
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);

-- =====================================================
-- 4. Indexes
-- =====================================================

CREATE INDEX IF NOT EXISTS "idx_testTrackerVR_questionId"
    ON "testTrackerVR" ("questionId");

CREATE INDEX IF NOT EXISTS "idx_testTrackerVR_testId"
    ON "testTrackerVR" ("testId");

CREATE INDEX IF NOT EXISTS "idx_testTrackerVR_studentId"
    ON "testTrackerVR" ("studentId");

CREATE INDEX IF NOT EXISTS "idx_testTrackerVRMain_studentId"
    ON "testTrackerVRMain" ("studentId");
